/**
 * Valid state machine transitions for PayU transactions.
 * A transaction in `SUCCESS` can NEVER transition back to `FAILED`, `PENDING`,
 * `CANCELLED`, `INITIATED`, or `EXPIRED` due to a delayed or duplicate callback.
 */
const ALLOWED_STATE_TRANSITIONS: Record<PaymentStatus, ReadonlySet<PaymentStatus>> = {
  CREATED: new Set(["CREATED", "INITIATED", "PENDING", "SUCCESS", "FAILED", "CANCELLED", "EXPIRED"]),
  INITIATED: new Set(["INITIATED", "PENDING", "SUCCESS", "FAILED", "CANCELLED", "EXPIRED"]),
  PENDING: new Set(["PENDING", "SUCCESS", "FAILED", "CANCELLED", "EXPIRED"]),
  SUCCESS: new Set(["SUCCESS", "REFUND_PENDING", "REFUNDED"]),
  FAILED: new Set(["FAILED", "SUCCESS"]), // Only server-verified late capture can upgrade FAILED -> SUCCESS
  CANCELLED: new Set(["CANCELLED", "SUCCESS"]),
  EXPIRED: new Set(["EXPIRED", "SUCCESS"]),
  REFUND_PENDING: new Set(["REFUND_PENDING", "REFUNDED"]),
  REFUNDED: new Set(["REFUNDED"]),
  NOT_APPLICABLE: new Set(["NOT_APPLICABLE"]),
};

export function canTransitionPaymentStatus(
  current: PaymentStatus,
  next: PaymentStatus
): boolean {
  const allowed = ALLOWED_STATE_TRANSITIONS[current];
  return allowed ? allowed.has(next) : false;
}

/**
 * In-process async mutex lock keyed by resource name (`txn:<txnid>`, `seq:mint`, etc.)
 * to guarantee atomic state transitions and unique Participant ID generation
 * under high concurrency.
 */
const activeLocks = new Map<string, Promise<unknown>>();

export async function withMutexLock<T>(key: string, fn: () => Promise<T>): Promise<T> {
  const prev = activeLocks.get(key) ?? Promise.resolve();
  let release!: () => void;
  const gate = new Promise<void>((resolve) => {
    release = resolve;
  });
  const current = prev.then(() => gate);
  activeLocks.set(key, current);

  await prev;
  try {
    return await fn();
  } finally {
    release();
    if (activeLocks.get(key) === current) {
      activeLocks.delete(key);
    }
  }
}

