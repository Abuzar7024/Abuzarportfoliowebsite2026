/**
 * Saves or updates participant profile details (Full Name, Email, WhatsApp) and associates
 * them with the verified PayU payment and Participant ID.
 */
export async function completeParticipantProfile(params: {
  participantId: string;
  payuTxnId: string;
  participantName: string;
  email: string;
  whatsappNumber: string;
}): Promise<AvatarRegistrationRecord> {
  return withMutexLock(`txn:${params.payuTxnId}`, async () => {
    const db = loadLocalDb();
    const record =
      db.recordsByTxnId[params.payuTxnId] ||
      (await getRegistrationByParticipantId(params.participantId));

    if (!record) {
      throw new Error("Registration record not found for this transaction.");
    }
    if (record.paymentStatus !== "SUCCESS" || !record.participantId) {
      throw new Error("Cannot complete profile for an unverified payment.");
    }
    if (record.participantId.toUpperCase() !== params.participantId.trim().toUpperCase()) {
      throw new Error("Participant ID mismatch.");
    }

    const now = new Date().toISOString();
    record.participantName = params.participantName.trim();
    record.email = params.email.trim();
    record.whatsappNumber = params.whatsappNumber.trim();
    record.profileCompletionStatus = "COMPLETED";
    record.registrationStatus = "COMPLETED";
    record.profileCompletedAt = record.profileCompletedAt ?? now;
    if (record.emailNotificationStatus === "NOT_STARTED") {
      record.emailNotificationStatus = "QUEUED";
    }
    record.updatedAt = now;
    record.verifySignature = signToken({
      pid: record.participantId,
      status: "VERIFIED",
    });

    db.recordsByTxnId[record.payuTxnId] = record;
    db.txnIdByParticipantId[record.participantId] = record.payuTxnId;
    saveLocalDb(db);
    await syncExternalStore(record);
    return record;
  });
}

export async function updateNotificationState(
  payuTxnId: string,
  patch: Partial<
    Pick<
      AvatarRegistrationRecord,
      | "emailNotificationStatus"
      | "participantEmailStatus"
      | "notificationRetryCount"
      | "lastNotificationError"
      | "nextRetryAt"
      | "backupAlertSent"
      | "backupAlertChannel"
    >
  >
): Promise<AvatarRegistrationRecord | null> {
  const db = loadLocalDb();
  const record = db.recordsByTxnId[payuTxnId];
  if (!record) return null;
  Object.assign(record, patch, { updatedAt: new Date().toISOString() });
  saveLocalDb(db);
  return record;
}

/** Returns records whose organiser notification is queued for retry. */
export function getPendingNotificationRecords(): AvatarRegistrationRecord[] {
  const db = loadLocalDb();
  const now = Date.now();
  return Object.values(db.recordsByTxnId).filter((r) => {
    if (r.profileCompletionStatus !== "COMPLETED") return false;
    if (
      r.emailNotificationStatus !== "QUEUED" &&
      r.emailNotificationStatus !== "FAILED_QUEUED"
    ) {
      return false;
    }
    if (r.notificationRetryCount >= 5) return false;
    if (r.nextRetryAt && Date.parse(r.nextRetryAt) > now) return false;
    return true;
  });
}
