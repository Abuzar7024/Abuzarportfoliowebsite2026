/**
 * Atomically and idempotently transitions a transaction state (`PENDING`, `SUCCESS`,
 * `FAILED`, `CANCELLED`, `EXPIRED`, `REFUND_PENDING`, `REFUNDED`).
 *
 * - Enforces the payment state machine: a `SUCCESS` transaction can NEVER be downgraded
 *   to `FAILED`, `PENDING`, or `CANCELLED` by a delayed or duplicate callback.
 * - Mints a unique `AIH-2026-XXXXXX` Participant ID under a mutex lock ONLY on confirmed `SUCCESS`.
 */
export async function recordPaymentOutcome(params: {
  payuTxnId: string;
  payuMihpayid?: string | null;
  status: PaymentStatus;
  failureReason?: string | null;
  amount?: string;
  firstname?: string;
  email?: string;
  phone?: string;
}): Promise<AvatarRegistrationRecord> {
  return withMutexLock(`txn:${params.payuTxnId}`, async () => {
    const db = loadLocalDb();
    const now = new Date().toISOString();

    if (params.payuMihpayid) {
      const existingTxnForMih = db.txnIdByMihpayid[params.payuMihpayid];
      if (existingTxnForMih && existingTxnForMih !== params.payuTxnId) {
        return db.recordsByTxnId[existingTxnForMih];
      }
    }

    let record = db.recordsByTxnId[params.payuTxnId];
    if (!record) {
      const sbRow = await fetchSupabaseByTxnId(params.payuTxnId);
      if (sbRow) {
        const profileComplete = hasCompleteContactDetails({
          participantName: sbRow.full_name,
          email: sbRow.email,
          whatsappNumber: sbRow.whatsapp_number,
        });
        record = {
          registrationRef: `REG-${sbRow.payu_txnid.slice(-8)}`,
          payuTxnId: sbRow.payu_txnid,
          payuMihpayid: sbRow.payu_mihpayid,
          idempotencyKey: null,
          participantId: sbRow.participant_id,
          participantName: sbRow.full_name,
          email: sbRow.email,
          whatsappNumber: sbRow.whatsapp_number,
          paymentAmount: sbRow.payment_amount,
          currency: "INR",
          paymentStatus: (sbRow.payment_status as PaymentStatus) || "INITIATED",
          registrationStatus:
            sbRow.payment_status === "SUCCESS"
              ? profileComplete
                ? "COMPLETED"
                : "AWAITING_PROFILE"
              : "PAYMENT_INITIATED",
          failureReason: null,
          badgeUrl: sbRow.participant_id
            ? `/competition/verify/${sbRow.participant_id}`
            : null,
          profileCompletionStatus: profileComplete ? "COMPLETED" : "PENDING",
          emailNotificationStatus: "NOT_STARTED",
          participantEmailStatus: "NOT_STARTED",
          notificationRetryCount: 0,
          lastNotificationError: null,
          nextRetryAt: null,
          backupAlertSent: false,
          backupAlertChannel: null,
          registrationTimestamp: sbRow.registered_at || now,
          paidAt: sbRow.paid_at,
          lastVerifiedAt: now,
          profileCompletedAt: profileComplete ? sbRow.registered_at || now : null,
          updatedAt: now,
          verifySignature: null,
        };
        db.recordsByTxnId[params.payuTxnId] = record;
      } else {
        const participantName = (params.firstname ?? "").trim();
        const email = (params.email ?? "").trim();
        const whatsappNumber = (params.phone ?? "").trim();
        const profileComplete = hasCompleteContactDetails({
          participantName,
          email,
          whatsappNumber,
        });
        record = {
          registrationRef: `REG-${params.payuTxnId.slice(-8)}`,
          payuTxnId: params.payuTxnId,
          payuMihpayid: null,
          idempotencyKey: null,
          participantId: null,
          participantName,
          email,
          whatsappNumber,
          paymentAmount:
            params.amount ?? `${AVATAR_COMPETITION.registration.feeInr}.00`,
          currency: "INR",
          paymentStatus: "INITIATED",
          registrationStatus: "PAYMENT_INITIATED",
          failureReason: null,
          badgeUrl: null,
          profileCompletionStatus: profileComplete ? "COMPLETED" : "PENDING",
          emailNotificationStatus: "NOT_STARTED",
          participantEmailStatus: "NOT_STARTED",
          notificationRetryCount: 0,
          lastNotificationError: null,
          nextRetryAt: null,
          backupAlertSent: false,
          backupAlertChannel: null,
          registrationTimestamp: now,
          paidAt: null,
          lastVerifiedAt: now,
          profileCompletedAt: profileComplete ? now : null,
          updatedAt: now,
          verifySignature: null,
        };
        db.recordsByTxnId[params.payuTxnId] = record;
      }
    }

    if (params.payuMihpayid) {
      record.payuMihpayid = params.payuMihpayid;
      db.txnIdByMihpayid[params.payuMihpayid] = record.payuTxnId;
    }
    if (params.firstname && !record.participantName) {
      record.participantName = params.firstname.trim();
    }
    if (params.email && !record.email) {
      record.email = params.email.trim();
    }
    if (params.phone && !record.whatsappNumber) {
      record.whatsappNumber = params.phone.trim();
    }
    if (
      hasCompleteContactDetails(record) &&
      record.profileCompletionStatus !== "COMPLETED"
    ) {
      record.profileCompletionStatus = "COMPLETED";
      record.profileCompletedAt = record.profileCompletedAt ?? now;
    }

    record.lastVerifiedAt = now;
    record.updatedAt = now;

    // Enforce Payment State Machine: NEVER downgrade a SUCCESS transaction
    if (
      record.paymentStatus === "SUCCESS" &&
      record.participantId &&
      params.status !== "REFUND_PENDING" &&
      params.status !== "REFUNDED"
    ) {
      saveLocalDb(db);
      await syncExternalStore(record);
      return record;
    }

    if (!canTransitionPaymentStatus(record.paymentStatus, params.status)) {
      saveLocalDb(db);
      return record;
    }

    record.paymentStatus = params.status;

    if (params.status === "SUCCESS") {
      record.failureReason = null;
      if (!record.participantId) {
        await withMutexLock("seq:mint", async () => {
          const prefix = AVATAR_COMPETITION.registration.idPrefix;
          let candidate = "";
          do {
            db.sequence += 1;
            candidate = `${prefix}-${String(db.sequence).padStart(6, "0")}`;
          } while (db.txnIdByParticipantId[candidate]);

          record!.participantId = candidate;
          db.txnIdByParticipantId[candidate] = record!.payuTxnId;
        });
      }
      record.paidAt = record.paidAt ?? now;
      record.badgeUrl = `/competition/verify/${record.participantId}`;
      record.registrationStatus =
        record.profileCompletionStatus === "COMPLETED"
          ? "COMPLETED"
          : "AWAITING_PROFILE";
      if (
        record.profileCompletionStatus === "COMPLETED" &&
        record.emailNotificationStatus === "NOT_STARTED"
      ) {
        record.emailNotificationStatus = "QUEUED";
      }
      record.verifySignature = signToken({
        pid: record.participantId!,
        status: "VERIFIED",
      });
    } else if (params.status === "PENDING") {
      record.registrationStatus = "PAYMENT_PENDING";
      if (params.failureReason) record.failureReason = params.failureReason;
    } else if (params.status === "FAILED" || params.status === "CANCELLED") {
      record.registrationStatus = "PAYMENT_FAILED";
      record.failureReason = params.failureReason || null;
    } else if (params.status === "EXPIRED") {
      record.registrationStatus = "EXPIRED";
      record.failureReason = params.failureReason || "Transaction expired";
    } else if (params.status === "REFUND_PENDING" || params.status === "REFUNDED") {
      record.registrationStatus = "REFUNDED";
    }

    saveLocalDb(db);
    await syncExternalStore(record);
    if (record.participantId) {
      db.txnIdByParticipantId[record.participantId] = record.payuTxnId;
    }
    return record;
  });
}

