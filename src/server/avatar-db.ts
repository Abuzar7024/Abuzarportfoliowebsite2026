/**
 * Signs a payload with HMAC-SHA256 for tamper-proof registration tokens
 * and stateless badge verification.
 */
export function signToken(payload: Record<string, string>): string {
  const data = Buffer.from(JSON.stringify(payload), "utf8").toString("base64url");
  const sig = crypto
    .createHmac("sha256", getSigningSecret())
    .update(data)
    .digest("base64url");
  return `${data}.${sig}`;
}

export function verifyToken<T extends Record<string, string>>(token: string): T | null {
  if (!token || !token.includes(".")) return null;
  const [data, sig] = token.split(".");
  if (!data || !sig) return null;
  const expected = crypto
    .createHmac("sha256", getSigningSecret())
    .update(data)
    .digest("base64url");
  const a = Buffer.from(sig);
  const b = Buffer.from(expected);
  if (a.length !== b.length || !crypto.timingSafeEqual(a, b)) return null;
  try {
    return JSON.parse(Buffer.from(data, "base64url").toString("utf8")) as T;
  } catch {
    return null;
  }
}

let memoryCache: DatabaseSchema | null = null;
let lastLoadedMtimeMs = 0;

function loadLocalDb(): DatabaseSchema {
  try {
    if (fs.existsSync(DB_FILE)) {
      const stat = fs.statSync(DB_FILE);
      if (memoryCache && stat.mtimeMs === lastLoadedMtimeMs) {
        return memoryCache;
      }
      const raw = fs.readFileSync(DB_FILE, "utf8");
      const parsed = JSON.parse(raw) as Partial<DatabaseSchema>;
      if (parsed && typeof parsed.sequence === "number" && parsed.recordsByTxnId) {
        memoryCache = {
          sequence: parsed.sequence,
          recordsByTxnId: parsed.recordsByTxnId || {},
          txnIdByParticipantId: parsed.txnIdByParticipantId || {},
          txnIdByMihpayid: parsed.txnIdByMihpayid || {},
          txnIdByIdempotencyKey: parsed.txnIdByIdempotencyKey || {},
        };
        lastLoadedMtimeMs = stat.mtimeMs;
        return memoryCache;
      }
    }
  } catch {
    if (memoryCache) return memoryCache;
  }
  memoryCache = {
    sequence: 0,
    recordsByTxnId: {},
    txnIdByParticipantId: {},
    txnIdByMihpayid: {},
    txnIdByIdempotencyKey: {},
  };
  return memoryCache;
}

function saveLocalDb(db: DatabaseSchema): void {
  memoryCache = db;
  try {
    fs.mkdirSync(DATA_DIR, { recursive: true });
    const tmpFile = `${DB_FILE}.tmp.${process.pid}.${Date.now()}.${crypto
      .randomBytes(3)
      .toString("hex")}`;
    fs.writeFileSync(tmpFile, JSON.stringify(db, null, 2), "utf8");
    fs.renameSync(tmpFile, DB_FILE);
    lastLoadedMtimeMs = fs.statSync(DB_FILE).mtimeMs;
  } catch {
    // In read-only serverless environments, memoryCache + Supabase handles persistence
  }
}

export function resetInMemoryDbCache(): void {
  memoryCache = null;
}

function hasCompleteContactDetails(r: {
  participantName?: string;
  email?: string;
  whatsappNumber?: string;
}): boolean {
  return Boolean(
    r.participantName &&
      r.participantName.trim().length >= 2 &&
      r.email &&
      r.email.includes("@") &&
      r.whatsappNumber &&
      r.whatsappNumber.replace(/\D/g, "").length >= 8
  );
}

/** Syncs the clean registration record to Supabase (`public.ai_hackathon_registrations`). */
async function syncExternalStore(record: AvatarRegistrationRecord): Promise<void> {
  const sbRow = await syncSupabaseRegistration({
    payuTxnId: record.payuTxnId,
    fullName: record.participantName,
    email: record.email,
    whatsappNumber: record.whatsappNumber,
    paymentAmount: record.paymentAmount,
    paymentStatus: record.paymentStatus,
    participantId: record.participantId,
    payuMihpayid: record.payuMihpayid,
    paidAt: record.paidAt,
    registrationRef: record.registrationRef,
    termsVersion: record.termsVersion || AVATAR_COMPETITION.registration.termsVersion,
    privacyVersion: record.privacyVersion || AVATAR_COMPETITION.registration.privacyVersion,
    consentTimestamp: record.consentTimestamp || record.registrationTimestamp,
    consentStatus: record.consentStatus || "ACCEPTED",
  });

  if (sbRow?.participant_id && !record.participantId) {
    record.participantId = sbRow.participant_id;
    record.badgeUrl = `/competition/verify/${sbRow.participant_id}`;
  }
}

/**
 * Returns the real, deduplicated confirmed pre-registration count (`paymentStatus === "SUCCESS"`).
 * Never uses fake or hardcoded counts.
 */
export async function getConfirmedPreRegistrationCount(): Promise<{
  confirmedCount: number;
  targetCount: number;
  percentage: number;
  targetReached: boolean;
}> {
  const targetCount = AVATAR_COMPETITION.registration.targetRegistrations || 5000;
  const db = loadLocalDb();
  const localEmails = new Set<string>();
  for (const rec of Object.values(db.recordsByTxnId)) {
    if (rec.paymentStatus === "SUCCESS" && rec.email) {
      localEmails.add(rec.email.trim().toLowerCase());
    }
  }

  const sbCount = await fetchSupabaseConfirmedCount();
  const confirmedCount =
    sbCount !== null ? Math.max(sbCount, localEmails.size) : localEmails.size;
  const percentage = Math.min(100, Number(((confirmedCount / targetCount) * 100).toFixed(2)));
  return {
    confirmedCount,
    targetCount,
    percentage,
    targetReached: confirmedCount >= targetCount,
  };
}

export function normalizeEmail(email: string): string {
  return (email || "").trim().toLowerCase();
}

export function normalizePhoneDigits(phone: string): string {
  const digits = (phone || "").replace(/\D/g, "");
  return digits.length >= 10 ? digits.slice(-10) : digits;
}

function hydrateRecordFromSupabaseRow(
  sbRow: SupabaseHackathonRow,
  db: DatabaseSchema
): AvatarRegistrationRecord {
  if (db.recordsByTxnId[sbRow.payu_txnid]) {
    return db.recordsByTxnId[sbRow.payu_txnid];
  }
  const profileComplete = hasCompleteContactDetails({
    participantName: sbRow.full_name,
    email: sbRow.email,
    whatsappNumber: sbRow.whatsapp_number,
  });
  const rec: AvatarRegistrationRecord = {
    registrationRef: sbRow.registration_ref || `REG-${sbRow.payu_txnid.slice(-8)}`,
    payuTxnId: sbRow.payu_txnid,
    payuMihpayid: sbRow.payu_mihpayid,
    idempotencyKey: null,
    participantId: sbRow.participant_id,
    participantName: sbRow.full_name,
    email: sbRow.email,
    whatsappNumber: sbRow.whatsapp_number,
    paymentAmount: sbRow.payment_amount,
    currency: "INR",
    paymentStatus: (sbRow.payment_status as PaymentStatus) || "INITIATED",
    registrationStatus:
      sbRow.payment_status === "SUCCESS"
        ? profileComplete
          ? "COMPLETED"
          : "AWAITING_PROFILE"
        : sbRow.payment_status === "PENDING"
        ? "PAYMENT_PENDING"
        : "PAYMENT_FAILED",
    failureReason: null,
    badgeUrl: sbRow.participant_id
      ? `/competition/verify/${sbRow.participant_id}`
      : null,
    profileCompletionStatus: profileComplete ? "COMPLETED" : "PENDING",
    emailNotificationStatus: "SENT",
    participantEmailStatus: "SENT",
    notificationRetryCount: 0,
    lastNotificationError: null,
    nextRetryAt: null,
    backupAlertSent: false,
    backupAlertChannel: null,
    registrationTimestamp: sbRow.registered_at,
    paidAt: sbRow.paid_at,
    lastVerifiedAt: sbRow.paid_at || sbRow.registered_at,
    profileCompletedAt: profileComplete ? sbRow.registered_at : null,
    updatedAt: sbRow.paid_at || sbRow.registered_at,
    verifySignature: sbRow.participant_id
      ? signToken({
          pid: sbRow.participant_id,
          status: "VERIFIED",
        })
      : null,
    termsVersion: sbRow.terms_version || AVATAR_COMPETITION.registration.termsVersion,
    privacyVersion: sbRow.privacy_version || AVATAR_COMPETITION.registration.privacyVersion,
    consentTimestamp: sbRow.consent_timestamp || sbRow.registered_at,
    consentStatus: (sbRow.consent_status as "ACCEPTED" | "NOT_PROVIDED") || "ACCEPTED",
  };
  db.recordsByTxnId[sbRow.payu_txnid] = rec;
  if (rec.participantId) {
    db.txnIdByParticipantId[rec.participantId] = sbRow.payu_txnid;
  }
  return rec;
}

/**
 * Checks for existing paid or active in-flight transactions for the same participant
 * (matching normalized email OR normalized mobile number across BOTH local DB and Supabase)
 * or idempotency key to prevent duplicate payments across browsers and cache clears.
 */
export async function findExistingParticipantTransaction(params: {
  email: string;
  whatsappNumber: string;
  idempotencyKey?: string | null;
}): Promise<{
  outcome: "NONE" | "ALREADY_PAID" | "IDEMPOTENT_REUSE" | "ACTIVE_UNRESOLVED";
  record: AvatarRegistrationRecord | null;
  identityFullyMatched: boolean;
}> {
  const db = loadLocalDb();
  const normEmail = normalizeEmail(params.email);
  const normPhone = normalizePhoneDigits(params.whatsappNumber);
  const now = Date.now();

  if (params.idempotencyKey) {
    const existingTxnId = db.txnIdByIdempotencyKey[params.idempotencyKey];
    if (existingTxnId && db.recordsByTxnId[existingTxnId]) {
      const rec = db.recordsByTxnId[existingTxnId];
      const bothMatch =
        normalizeEmail(rec.email) === normEmail &&
        normalizePhoneDigits(rec.whatsappNumber) === normPhone;
      if (rec.paymentStatus === "SUCCESS") {
        return { outcome: "ALREADY_PAID", record: rec, identityFullyMatched: bothMatch };
      }
      const ageMs = now - Date.parse(rec.registrationTimestamp);
      if (
        (rec.paymentStatus === "CREATED" || rec.paymentStatus === "INITIATED") &&
        ageMs < 10 * 60 * 1000
      ) {
        return { outcome: "IDEMPOTENT_REUSE", record: rec, identityFullyMatched: bothMatch };
      }
    }
  }

  let latestUnresolved: AvatarRegistrationRecord | null = null;
  let unresolvedBothMatch = false;

  for (const rec of Object.values(db.recordsByTxnId)) {
    const sameEmail = normEmail.length > 0 && normalizeEmail(rec.email) === normEmail;
    const samePhone =
      normPhone.length >= 8 && normalizePhoneDigits(rec.whatsappNumber) === normPhone;
    if (!sameEmail && !samePhone) continue;

    if (rec.paymentStatus === "SUCCESS" && rec.participantId) {
      return {
        outcome: "ALREADY_PAID",
        record: rec,
        identityFullyMatched: sameEmail && samePhone,
      };
    }

    const ageMs = now - Date.parse(rec.registrationTimestamp);
    if (
      (rec.paymentStatus === "PENDING" || rec.paymentStatus === "INITIATED") &&
      ageMs < 15 * 60 * 1000
    ) {
      if (
        !latestUnresolved ||
        Date.parse(rec.registrationTimestamp) >
          Date.parse(latestUnresolved.registrationTimestamp)
      ) {
        latestUnresolved = rec;
        unresolvedBothMatch = sameEmail && samePhone;
      }
    }
  }

  // Also query Supabase Postgres so clearing browser cache/localStorage or switching servers never allows duplicate registration
  const sbRow = await fetchSupabaseByIdentity(normEmail, normPhone);
  if (sbRow) {
    const rec = hydrateRecordFromSupabaseRow(sbRow, db);
    const sameEmail = normEmail.length > 0 && normalizeEmail(rec.email) === normEmail;
    const samePhone =
      normPhone.length >= 8 && normalizePhoneDigits(rec.whatsappNumber) === normPhone;
    if (rec.paymentStatus === "SUCCESS" && rec.participantId) {
      return {
        outcome: "ALREADY_PAID",
        record: rec,
        identityFullyMatched: sameEmail && samePhone,
      };
    }
    const ageMs = now - Date.parse(rec.registrationTimestamp);
    if (
      !latestUnresolved &&
      (rec.paymentStatus === "PENDING" || rec.paymentStatus === "INITIATED") &&
      ageMs < 15 * 60 * 1000
    ) {
      latestUnresolved = rec;
      unresolvedBothMatch = sameEmail && samePhone;
    }
  }

  if (latestUnresolved) {
    return {
      outcome: "ACTIVE_UNRESOLVED",
      record: latestUnresolved,
      identityFullyMatched: unresolvedBothMatch,
    };
  }

  return { outcome: "NONE", record: null, identityFullyMatched: false };
}

/**
 * Recovers a confirmed paid registration across any browser/device when a participant
 * provides both their registered Email and WhatsApp number.
 */
export async function recoverRegistrationByIdentity(params: {
  email: string;
  whatsappNumber: string;
}): Promise<AvatarRegistrationRecord | null> {
  const db = loadLocalDb();
  const normEmail = normalizeEmail(params.email);
  const normPhone = normalizePhoneDigits(params.whatsappNumber);
  if (!normEmail || normPhone.length < 8) return null;

  for (const rec of Object.values(db.recordsByTxnId)) {
    if (
      rec.paymentStatus === "SUCCESS" &&
      rec.participantId &&
      normalizeEmail(rec.email) === normEmail &&
      normalizePhoneDigits(rec.whatsappNumber) === normPhone
    ) {
      return rec;
    }
  }

  const sbRow = await fetchSupabaseByIdentity(normEmail, normPhone);
  if (sbRow && sbRow.payment_status === "SUCCESS" && sbRow.participant_id) {
    const rec = hydrateRecordFromSupabaseRow(sbRow, db);
    if (
      normalizeEmail(rec.email) === normEmail &&
      normalizePhoneDigits(rec.whatsappNumber) === normPhone
    ) {
      return rec;
    }
  }

  return null;
}

/**
 * Creates a persistent payment record (`CREATED` -> `INITIATED`) before redirecting to PayU.
 */
export async function createInitiatedTransaction(params: {
  payuTxnId: string;
  participantName?: string;
  email?: string;
  whatsappNumber?: string;
  amount: string;
  idempotencyKey?: string | null;
  termsVersion?: string | null;
  privacyVersion?: string | null;
  consentTimestamp?: string | null;
  consentStatus?: "ACCEPTED" | "NOT_PROVIDED";
}): Promise<AvatarRegistrationRecord> {
  return withMutexLock(`txn:${params.payuTxnId}`, async () => {
    const db = loadLocalDb();
    if (db.recordsByTxnId[params.payuTxnId]) {
      return db.recordsByTxnId[params.payuTxnId];
    }

    const now = new Date().toISOString();
    const participantName = (params.participantName ?? "").trim();
    const email = (params.email ?? "").trim();
    const whatsappNumber = (params.whatsappNumber ?? "").trim();
    const profileComplete = hasCompleteContactDetails({
      participantName,
      email,
      whatsappNumber,
    });

    const regRef = `REG-${Date.now().toString(36).toUpperCase()}-${crypto
      .randomBytes(3)
      .toString("hex")
      .toUpperCase()}`;

    // Step 1: Persistent order created -> transitioned to INITIATED for checkout
    const record: AvatarRegistrationRecord = {
      registrationRef: regRef,
      payuTxnId: params.payuTxnId,
      payuMihpayid: null,
      idempotencyKey: params.idempotencyKey || null,
      participantId: null,
      participantName,
      email,
      whatsappNumber,
      paymentAmount: params.amount,
      currency: "INR",
      paymentStatus: "INITIATED",
      registrationStatus: "PAYMENT_INITIATED",
      failureReason: null,
      badgeUrl: null,
      profileCompletionStatus: profileComplete ? "COMPLETED" : "PENDING",
      emailNotificationStatus: "NOT_STARTED",
      participantEmailStatus: "NOT_STARTED",
      notificationRetryCount: 0,
      lastNotificationError: null,
      nextRetryAt: null,
      backupAlertSent: false,
      backupAlertChannel: null,
      registrationTimestamp: now,
      paidAt: null,
      lastVerifiedAt: now,
      profileCompletedAt: profileComplete ? now : null,
      updatedAt: now,
      verifySignature: null,
      termsVersion: params.termsVersion || AVATAR_COMPETITION.registration.termsVersion,
      privacyVersion: params.privacyVersion || AVATAR_COMPETITION.registration.privacyVersion,
      consentTimestamp: params.consentTimestamp || now,
      consentStatus: params.consentStatus || "ACCEPTED",
    };

    db.recordsByTxnId[params.payuTxnId] = record;
    if (params.idempotencyKey) {
      db.txnIdByIdempotencyKey[params.idempotencyKey] = params.payuTxnId;
    }
    saveLocalDb(db);
    await syncExternalStore(record);
    return record;
  });
}

